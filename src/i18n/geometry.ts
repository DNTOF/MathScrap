const ORDERED = Object.entries(PHRASE).sort((a, b) => b[0].length - a[0].length)

export function localizeGeo(text: string): string {
  if (!text || getLang() !== 'en') return text
  let out = text
  out = out.replace(/^含未知量 (.+)，但还没有条件。暂按 (.+) 绘图——试着加上「过\(1, 3\)」或「AB ⊥ BC」。$/, 'Unknowns $1, but no conditions yet. Plotting with $2 for now. Try 过(1, 3) or AB ⊥ BC.')
  out = out.replace(/^条件里有无法解析的内容：(.+)$/, 'A condition could not be parsed: $1')
  out = out.replace(/^条件比未知量少 (\d+) 个，解不唯一；这里展示其中一组。$/, '$1 fewer conditions than unknowns, so the solution is not unique. One of them is shown.')
  out = out.replace(/^共有 (\d+) 组解，可在上方切换。$/, '$1 solutions. Switch among them above.')
  out = out.replace(/^联立 (\d+) 个方程 · Rust 多起点 LM 求解$/, '$1 equations together · Rust multi-start LM')
  out = out.replace(/^第 (\d+) \/ (\d+) 组解$/, 'solution $1 / $2')
  out = out.replace(/^先写出 (.+) 的坐标，再定义 (.+)$/, 'Write coordinates for $1 before defining $2')
  out = out.replace(/^点 (.+) 已经定义过了$/, 'Point $1 is already defined')
  out = out.replace(/^先定义向量 (.+)（粗体名 = \(…\)），再定义 (.+)$/, 'Define vector $1 (a bold name = (…)) before defining $2')
  out = out.replace(/^点 (.+) 的坐标无法求值$/, 'The coordinates of point $1 could not be evaluated')
  out = out.replace(/^⊙(.+) 的半径$/, 'radius of ⊙$1')
  out = out.replace(/^看作 y = (.+) 与 x 轴的交点$/, 'Treated as the intersections of y = $1 with the x-axis')
  out = out.replace(/^在 \[(-?\d+), (\d+)\] 内没有实根$/, 'No real root in [$1, $2]')
  out = out.replace(/^在 \[(-?\d+), (\d+)\] 内$/, 'Inside [$1, $2]')
  out = out.replace(/^直线 (.+)$/, 'Line $1')
  out = out.replace(/^函数 (.+)$/, 'Function $1')
  out = out.replace(/^方程 (.+)$/, 'Equation $1')
  out = out.replace(/^曲线 (.+)$/, 'Curve $1')
  out = out.replace(/^曲面 (.+)$/, 'Surface $1')
  out = out.replace(/^向量 (.+)$/, 'Vectors $1')
  out = out.replace(/^平面 (.+)$/, 'Plane $1')
  for (const [zh, en] of ORDERED) {
    if (out.includes(zh)) out = out.split(zh).join(en)
  }
  return out
}
